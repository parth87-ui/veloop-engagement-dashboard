"""Generate number-bearing Markdown docs from the output tables (no hand transcription).

Writes docs/kpi_catalogue.md, docs/findings.md, docs/recommendations.md, docs/data_dictionary.md,
docs/chart_catalogue.md and refreshes the auto-generated block in README.md.
"""
from __future__ import annotations

import re

import pandas as pd

from analysis import config
from analysis.pipeline.context import Context

DOCS = config.ROOT / "docs"
NOTE = "> Auto-generated by `analysis/pipeline/s23_docs.py` from `outputs/tables`. All values come from the **simulated** dataset.\n"


def md_table(df: pd.DataFrame, cols=None, headers=None) -> str:
    df = df[cols] if cols else df
    headers = headers or list(df.columns)
    esc = lambda v: "" if pd.isna(v) else str(v).replace("|", "\\|").replace("\n", " ")  # noqa: E731
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(esc(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return "\n".join(lines) + "\n"


def run(ctx: Context) -> None:
    DOCS.mkdir(exist_ok=True)
    T = config.OUT_TABLES
    rd = lambda n: pd.read_csv(T / f"{n}.csv")  # noqa: E731

    kpi = rd("kpi_catalogue")
    out = ["# KPI Catalogue\n", NOTE, f"{len(kpi)} behavioural KPIs. *Current value* is the value in the simulated dataset.\n"]
    for cat, g in kpi.groupby("category", sort=False):
        out.append(f"\n## {cat}\n")
        out.append(md_table(g, ["kpi_id", "kpi_name", "definition", "formula", "unit", "denominator", "data_source",
                                "current_value_simulated", "interpretation", "limitation"],
                            ["ID", "KPI", "Definition", "Formula", "Unit", "Denominator", "Source", "Current (simulated)",
                             "Interpretation", "Limitation"]))
    (DOCS / "kpi_catalogue.md").write_text("".join(out), encoding="utf-8")

    f = rd("behavioral_findings")
    out = ["# Behavioral Findings, Friction & Opportunities\n", NOTE,
           "Each finding follows **Observation → Evidence → Interpretation → Limitation → Product implication**. "
           "Observations/evidence are *simulated data results*; interpretations are *analyst interpretation*; implications "
           "are *product hypotheses*. Correlation is never presented as causation.\n"]
    for r in f.itertuples():
        out.append(f"\n### {r.finding_id} — {r.title}\n*Theme: {r.theme} · Confidence: {r.confidence}*\n\n"
                   f"- **Observation:** {r.observation}\n- **Evidence:** {r.evidence}\n- **Interpretation:** {r.interpretation}\n"
                   f"- **Limitation:** {r.limitation}\n- **Product implication:** {r.product_implication}\n")
    out.append("\n## Product Friction Register\n\nExplanations are hypotheses; none is confirmed by the dataset.\n\n")
    out.append(md_table(rd("product_friction_register"), ["issue_id", "behavioral_signal", "affected_users", "evidence",
                                                          "possible_explanations", "confidence", "product_area", "investigation_needed"]))
    out.append("\n## Product Opportunity Register\n\nPriority = reach + severity + confidence + ease + relevance (each 1–3); "
               "High ≥ 12, Medium 9–11, Low ≤ 8.\n\n")
    out.append(md_table(rd("product_opportunity_register"), ["opportunity_id", "finding", "evidence", "user_problem",
                                                             "product_hypothesis", "proposed_investigation", "expected_impact_area",
                                                             "affected_population", "priority_score", "priority", "measurement"]))
    (DOCS / "findings.md").write_text("".join(out), encoding="utf-8")

    out = ["# Recommendations, Proposed Experiments & Tracking Gaps\n", NOTE,
           "\n## Final product analytics recommendations\n\n",
           md_table(rd("final_recommendations")),
           "\n## Proposed experiments\n\n**PROPOSED EXPERIMENTS — none of these was run.**\n"]
    for r in rd("proposed_experiments").itertuples():
        out.append(f"\n### {r.experiment_id} (PROPOSED EXPERIMENT)\n\n| Field | Value |\n|---|---|\n"
                   f"| Hypothesis | {r.hypothesis} |\n| Problem (evidence) | {r.problem_evidence} |\n| Target users | {r.target_users} |\n"
                   f"| Control | {r.control} |\n| Variant | {r.variant} |\n| Primary metric | {r.primary_metric} |\n"
                   f"| Baseline (simulated) | {r.baseline_metric}: {r.baseline_value_pct}% |\n"
                   f"| Minimum detectable effect → target | +{r.minimum_detectable_effect_pp} pp → {r.target_value_pct}% |\n"
                   f"| Sample size | {r.sample_size_per_arm:,} per arm (unit: {r.randomisation_unit}) |\n"
                   f"| Duration at simulated volume | ≈{r.est_duration_days_at_simulated_volume:,} days "
                   f"({r.eligible_units_per_day_simulated} eligible units/day) – recompute with production traffic |\n"
                   f"| Analysis | {r.analysis_method} |\n| Decision rule | {r.decision_rule} |\n"
                   f"| Secondary metrics | {r.secondary_metrics} |\n| Guardrail metrics | {r.guardrail_metrics} |\n"
                   f"| Expected behavioural change | {r.expected_behavioral_change} |\n| Required event tracking | {r.required_event_tracking} |\n")
    out.append("\n## Event tracking gaps (PROPOSED analytics events)\n\n")
    out.append(md_table(rd("event_tracking_gaps"), ["event_name", "trigger", "required_properties", "why_needed", "kpi_supported"]))
    (DOCS / "recommendations.md").write_text("".join(out), encoding="utf-8")

    cp = pd.read_csv(T / "dq_column_profile.csv")
    dd = ctx.raw["dictionary"]
    out = ["# Data Dictionary\n", NOTE,
           "\n## Source workbook fields (profiled)\n\nPersonal fields in `01_Users_1000` are listed but never profiled, exported or displayed.\n\n",
           md_table(cp, ["sheet", "column", "dtype", "nulls", "null_pct", "unique_values", "top_values_or_range"]),
           "\n## Supplied dictionary (08_Data_Dictionary)\n\n", md_table(dd),
           "\n## Derived analytical fields (data/analytical/users_analytical.csv)\n\n"]
    derived = [
        ("n_sessions / n_valid_sessions", "Sessions / sessions with ≥1 raw feature event"),
        ("n_events", "Clean feature events (17 identical duplicates excluded)"),
        ("n_active_days", "Distinct calendar days with ≥1 feature event"),
        ("n_features / n_features_completed", "Distinct features used / with ≥1 'complete'-stage event"),
        ("n_meaningful", "Meaningful completion events (see methodology)"),
        ("n_meaningful_days_all", "Distinct days with a meaningful event or completed task"),
        ("first_activity_dt / last_activity_dt", "Earliest / latest session or event timestamp"),
        ("first_meaningful_dt", "Earliest meaningful event or task completion"),
        ("hours_to_first_activity / _session / _meaningful", "Hours from registration_datetime"),
        ("n_active_weeks / observable_weeks", "Distinct 7-day blocks with activity since first active day / blocks observable"),
        ("is_activated / activation_eligible", f"First meaningful activity within {ctx.R['activation']['window_days']} days of registration / full window observable"),
        ("activation_speed", "Within 24h · Day 2–7 · After day 7 · Never"),
        ("is_multi_feature", f"≥{ctx.R['thresholds']['multi_feature_min_completed_features']} features completed (P75)"),
        ("is_regular", f"Active in ≥{ctx.R['thresholds']['regular_engagement_min_weeks']} distinct weeks"),
        ("segment", "Mutually exclusive behavioural segment (methodology §Segmentation)"),
        ("engagement_score + c_* components", "Analyst-Created Simulated Engagement Score (0–100) and scaled components"),
        ("D1/D7/D14/D30_return, *_eligible", "Return flags anchored on first active date; NaN when the window is not observable"),
        ("current_level, xp_balance", "Not supported by available dataset"),
    ]
    out.append(md_table(pd.DataFrame(derived, columns=["Field", "Definition"])))
    (DOCS / "data_dictionary.md").write_text("".join(out), encoding="utf-8")

    out = ["# Metric Reconciliation\n", NOTE,
           "\nNumbers that look alike but use different definitions or denominators. Stages with the same name have identical "
           "counts in the lifecycle, activation funnel, engagement funnel and dashboard (single definition in "
           "`analysis/utils/funnel.py`).\n\n",
           md_table(rd("metric_reconciliation"), headers=["ID", "Metrics compared", "Value A", "Value B", "Definition difference",
                                                         "Why they differ"]),
           "\n## Canonical journey stages\n\n",
           md_table(rd("engagement_funnel"), ["stage", "definition", "users", "pct_of_registered", "users_standalone"],
                    ["Stage", "Definition", "Users (cumulative)", "% of registered", "Users (standalone)"]),
           "\n## Primary retention table (first active date anchor)\n\n", md_table(rd("return_rates_overall")),
           "\n## Comparison only: registration-date anchor\n\n", md_table(rd("return_rates_registration_anchor_comparison"))]
    (DOCS / "metric_reconciliation.md").write_text("".join(out), encoding="utf-8")

    cc = rd("chart_catalogue")
    out = ["# Chart Catalogue\n", NOTE]
    for r in cc.itertuples():
        out.append(f"\n## {r.chart_id} — {r.chart_name}\n\n![{r.chart_name}](../{r.file})\n\n| Field | Value |\n|---|---|\n"
                   + "".join(f"| {lab} | {str(getattr(r, k)).replace('|', '/')} |\n" for k, lab in [
                       ("business_question", "Business question"), ("dataset", "Dataset"), ("fields_used", "Fields used"),
                       ("calculation", "Calculation"), ("filter", "Filter"), ("population", "Population"),
                       ("time_period", "Time period"), ("interpretation", "Interpretation"), ("limitation", "Limitation"),
                       ("product_relevance", "Product relevance")]))
    (DOCS / "chart_catalogue.md").write_text("".join(out), encoding="utf-8")

    # README auto block
    readme = config.ROOT / "README.md"
    if readme.exists():
        R = ctx.R
        k, ret, sm = R["executive_kpis"], R["retention"]["overall"], R["sessions"]["metrics"]
        to = R["features"]["task_overall"]
        block = (
            "<!-- AUTO:START (generated by analysis/pipeline/s23_docs.py – do not edit by hand) -->\n"
            "| Headline metric (simulated dataset) | Value |\n|---|---|\n"
            f"| Registered / active users | {k['total_users']:,} / {k['active_users']:,} |\n"
            f"| Sessions · active user-days | {k['sessions']:,} · {k['active_user_days']:,} |\n"
            f"| Avg sessions per user | {k['avg_sessions_per_user']:.2f} |\n"
            f"| Repeat-user rate (≥2 active days) | {k['repeat_user_rate_pct']}% |\n"
            f"| Multi-feature user rate | {k['multi_feature_user_rate_pct']}% |\n"
            f"| Activation rate ({k['activation_window_days']}-day) | {k['activation_rate_pct']}% |\n"
            f"| D1 / D7 / D14 / D30 return | {ret['D1_rate_pct']}% / {ret['D7_rate_pct']}% / {ret['D14_rate_pct']}% / {ret['D30_rate_pct']}% |\n"
            f"| Median session duration | {sm['median_session_duration_s']:.0f} s |\n"
            f"| Task completion rate (resolved) | {to['completion_rate_resolved_pct']}% |\n"
            f"| Findings · KPIs · experiments · charts | {len(R['insights']['findings'])} · {R['kpis']['count']} · "
            f"{len(R['insights']['experiments'])} · {len(R['charts']['catalogue'])} |\n"
            "<!-- AUTO:END -->"
        )
        txt = readme.read_text(encoding="utf-8")
        txt = re.sub(r"<!-- AUTO:START.*?<!-- AUTO:END -->", lambda _: block, txt, flags=re.S)
        readme.write_text(txt, encoding="utf-8")
